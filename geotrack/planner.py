"""Route planning: candidate fixed-wing routes scored by expected information gain.

Candidates are generated by rolling out turn-rate-limited (Dubins-feasible)
fixed-wing kinematics: a fan of two-segment constant-turn manoeuvres, pursuit
routes to the highest-value regions of the belief, pursuit of each track's
predicted position, and the remainder of the current route.

Each candidate is scored by the expected reduction in total belief uncertainty
(objective "entropy", the default), in nats, discounted by time:

    w_search * sum over cells first swept of H(cell occupied by an undiscovered target)
  + w_track  * sum over tracks of P(re-observe) x H(track position forecast at that time)

Observing a cell with perfect sensing removes its uncertainty; re-observing a
tracked target collapses its position entropy. Because the advection-diffusion
prediction regrows uncertainty in cleared ground, minimising it drives both
spreading out and revisiting.

The alternative objective "detections" scores E[new detections] x H(where an
undiscovered target is), with entropies over footprint-sized bins; it favours the
highest-intensity ground and tends to concentrate agents.

after first removing everything teammates' committed legs are already expected
to observe. That conditioning is the coordination mechanism: no central
allocator, each agent simply plans around what others have promised to cover.
"""
from __future__ import annotations

import numpy as np
from scipy import ndimage

from .belief import cell_entropy
from .world import World


def wrap(a):
    return (a + np.pi) % (2 * np.pi) - np.pi


class Kinematics:
    def __init__(self, world: World, cfg: dict):
        a = cfg["agents"]
        self.g = world.grid
        self.dt = cfg["sim"]["dt_s"]
        self.v = a["speed"]
        self.r_min = a["min_turn_radius"]
        self.omega = self.v / self.r_min
        self.margin = 2.5 * self.r_min

    def rollout(self, x0, y0, h0, n, rates=None, goals=None, sub=5):
        """Vectorised rollout of C candidates for n steps -> (C, n, 3) poses at the end of each step."""
        C = len(rates) if rates is not None else len(goals)
        x, y, h = np.full(C, float(x0)), np.full(C, float(y0)), np.full(C, float(h0))
        out = np.empty((C, n, 3))
        dts = self.dt / sub
        W, H = self.g.size_x, self.g.size_y
        for s in range(n):
            for _ in range(sub):
                if goals is not None:
                    gx, gy = goals[:, 0], goals[:, 1]
                    err = wrap(np.arctan2(gy - y, gx - x) - h)
                    w = np.where(np.hypot(gx - x, gy - y) < 1.5 * self.r_min, self.omega, 1.5 * err)
                else:
                    w = rates[:, s]
                near = (x < self.margin) | (x > W - self.margin) | (y < self.margin) | (y > H - self.margin)
                dc = wrap(np.arctan2(H / 2 - y, W / 2 - x) - h)
                w = np.where(near & (np.abs(dc) > 0.4 * np.pi), np.sign(dc) * self.omega, w)
                w = np.clip(w, -self.omega, self.omega)
                h = wrap(h + w * dts)
                x = x + self.v * np.cos(h) * dts
                y = y + self.v * np.sin(h) * dts
            out[:, s, 0], out[:, s, 1], out[:, s, 2] = x, y, h
        return out


class InfoPlanner:
    """Coordinated information-gain planner. `greedy=True` gives the myopic, uncoordinated baseline."""

    def __init__(self, world: World, cfg: dict, greedy: bool = False):
        p, a = cfg["planner"], cfg["agents"]
        self.g = world.grid
        self.kin = Kinematics(world, cfg)
        self.dt = cfg["sim"]["dt_s"]
        self.leg = max(1, int(round(p["leg_s"] / self.dt)))
        self.greedy = greedy
        self.H = 2 * self.leg if greedy else max(self.leg, int(round(p["horizon_s"] / self.dt)))
        self.stride = int(p["eval_stride"])
        self.gamma = p["discount_per_min"] ** (self.dt / 60.0)
        self.R = a["footprint_m"]
        self.pd = a["pd"]
        self.w_search, self.w_track = p["w_search"], p["w_track"]
        self.objective = p.get("objective", "entropy")
        self.n_goals = 0 if greedy else int(p["n_goals"])
        self.n_part = int(p["plan_particles"])
        self.dy, self.dx = self.g.disc_offsets(self.R)
        self.seed = cfg["seed"]
        self.bin = max(1, int(round(self.R / self.g.cell)))
        self.bins_x = -(-self.g.nx // self.bin)

    def _bins(self, cells):
        iy, ix = np.divmod(cells, self.g.nx)
        return (iy // self.bin) * self.bins_x + ix // self.bin

    def _entropy(self, cells):
        _, c = np.unique(self._bins(cells), return_counts=True)
        p = c / c.sum()
        return float(-(p * np.log(p)).sum())

    def _intensity_entropy(self, lam):
        w = np.bincount(self._bins(np.arange(self.g.N)), weights=lam)
        p = w[w > 0] / w.sum()
        return float(-(p * np.log(p)).sum())

    # ---------------------------------------------------------------- helpers
    def _disc_idx(self, pts):
        """pts (..., 2) -> (..., D) flat cell indices of the footprint disc; N for off-grid cells."""
        g = self.g
        ix = np.floor(pts[..., 0] / g.cell).astype(np.int64)[..., None] + self.dx
        iy = np.floor(pts[..., 1] / g.cell).astype(np.int64)[..., None] + self.dy
        ok = (ix >= 0) & (ix < g.nx) & (iy >= 0) & (iy < g.ny)
        return np.where(ok, iy * g.nx + ix, g.N)

    def _eval_idx(self, n):
        return np.arange(self.stride - 1, n, self.stride)

    def covered_cells(self, routes):
        """Union of footprint cells over a list of (k, >=2) position arrays."""
        cells = [self._disc_idx(r[self.stride - 1::self.stride, :2]).ravel() for r in routes if len(r)]
        if not cells:
            return np.empty(0, dtype=np.int64)
        c = np.unique(np.concatenate(cells))
        return c[c < self.g.N]

    # ------------------------------------------------------------------- plan
    def plan(self, agent, step: int):
        g, kin, n = self.g, self.kin, self.H
        team = [] if self.greedy else agent.committed_routes(step)
        lam = agent.search.lam.copy()
        cov = self.covered_cells(team)
        lam[cov] *= (1.0 - self.pd)

        ev = self._eval_idx(n)
        hsteps = ev + 1
        track_data = []
        for tr in agent.tracks.tracks.values():
            F = agent.tracks.forecast(tr, n, self.stride, self.n_part, [self.seed, agent.id, tr.tid, step])
            cells = g.index(F[..., 0], F[..., 1])
            if self.objective == "detections":
                Hk = np.array([self._entropy(cells[:, j]) for j in range(cells.shape[1])])
            else:
                # Uncertainty this track adds to the map now; re-observing it removes it.
                Hk = np.full(cells.shape[1], agent.search.model.track_uncertainty(tr.cells))
            covered = np.zeros(len(F), bool)
            for r in team:
                m = min(len(ev), len(r) // self.stride)
                if m:
                    tp = r[ev[:m], :2]
                    covered |= (((F[:, :m] - tp[None]) ** 2).sum(-1) <= self.R ** 2).any(1)
            track_data.append((tr, F, Hk, covered))

        # --- candidates
        cands = []
        r = np.array([-1.0, -0.5, 0.0, 0.5, 1.0]) * kin.omega
        r1, r2 = np.meshgrid(r, r, indexing="ij")
        rates = np.zeros((r1.size, n))
        rates[:, :self.leg] = r1.ravel()[:, None]
        rates[:, self.leg:3 * self.leg] = r2.ravel()[:, None]
        cands.append(kin.rollout(agent.x, agent.y, agent.h, n, rates=rates))
        goals = self._value_goals(self._cell_value(lam), track_data) if self.n_goals else np.empty((0, 2))
        if not self.greedy:
            tg = [self._track_goal(agent, F, ev) for _, F, _, _ in track_data]
            if tg:
                goals = np.vstack([goals, np.array(tg)])
        if len(goals):
            cands.append(kin.rollout(agent.x, agent.y, agent.h, n, goals=goals))
        prev = None
        if agent.route is not None and agent.route_i < len(agent.route):
            rem = agent.route[agent.route_i:agent.route_i + n]
            if len(rem) < n:
                ext = kin.rollout(*rem[-1], n - len(rem), rates=np.zeros((1, n - len(rem))))[0]
                rem = np.vstack([rem, ext])
            prev = sum(len(c) for c in cands)
            cands.append(rem[None])
        routes = np.concatenate(cands)

        score = self._score(routes, self._cell_value(lam), track_data, ev, hsteps)
        if prev is not None:
            score[prev] *= 1.03   # mild hysteresis: do not churn between near-equal plans
        return routes[int(np.argmax(score))]

    def _cell_value(self, lam):
        """Per-cell value of looking: uncertainty removed (entropy) or weighted expected detections."""
        if self.objective == "detections":
            h_u = self._intensity_entropy(lam) if lam.sum() > 1e-9 else 0.0
            return h_u * lam * self.pd
        return cell_entropy(lam) * self.pd

    def _score(self, routes, cell_value, track_data, ev, hsteps):
        g = self.g
        C = len(routes)
        P = routes[:, ev, :2]
        idx = self._disc_idx(P)                                  # (C, Hs, D)
        tmin = np.full((C, g.N + 1), np.iinfo(np.int16).max, dtype=np.int16)
        crep = np.broadcast_to(np.arange(C)[:, None, None], idx.shape).ravel()
        hrep = np.broadcast_to(hsteps[None, :, None].astype(np.int16), idx.shape).ravel()
        np.minimum.at(tmin, (crep, idx.ravel()), hrep)
        seen = tmin[:, :g.N] < np.iinfo(np.int16).max
        G = np.where(seen, self.gamma ** tmin[:, :g.N].astype(np.float32), 0.0)
        with np.errstate(all="ignore"):   # spurious FP flags from some BLAS builds
            search = G @ cell_value

        track = np.zeros(C)
        for _, F, Hk, covered in track_data:
            d2 = ((P[:, None, :, :] - F[None, :, :, :]) ** 2).sum(-1)   # (C, Pp, Hs)
            hit = d2 <= self.R ** 2
            anyhit = hit.any(2) & ~covered[None, :]
            first = hit.argmax(2)
            track += np.where(anyhit, self.gamma ** hsteps[first] * Hk[first], 0.0).mean(1)

        outside = ~g.inside(routes[..., 0], routes[..., 1])
        return self.w_search * search + self.w_track * track - 10.0 * outside.mean(1)

    def _value_goals(self, cell_value, track_data):
        g = self.g
        V = self.w_search * cell_value
        for tr, F, Hk, covered in track_data:
            cells = g.index(F[:, -1, 0], F[:, -1, 1])
            np.add.at(V, cells, self.w_track * Hk[-1] * (~covered) / len(F))
        k = int(2 * self.R / g.cell) + 1
        V = ndimage.uniform_filter(V.reshape(g.ny, g.nx), size=k, mode="constant") * k * k
        peaks = (V == ndimage.maximum_filter(V, size=int(1500 / g.cell))) & (V > 1e-4)
        flat = np.flatnonzero(peaks.ravel())
        top = flat[np.argsort(V.ravel()[flat])[::-1][: self.n_goals]]
        return np.column_stack([g.cx[top], g.cy[top]])

    def _track_goal(self, agent, F, ev):
        mean = F.mean(0)                                        # (Hs, 2)
        reach = self.kin.v * (ev + 1) * self.dt
        d = np.hypot(mean[:, 0] - agent.x, mean[:, 1] - agent.y)
        j = int(np.argmax(d <= reach)) if (d <= reach).any() else len(ev) - 1
        return mean[j]


class LawnmowerPlanner:
    """Fixed-pattern coverage baseline: each agent sweeps its own vertical strip, forever."""

    def __init__(self, world: World, cfg: dict, n_agents: int):
        self.g = world.grid
        self.kin = Kinematics(world, cfg)
        self.n_agents = n_agents
        self.R = cfg["agents"]["footprint_m"]
        self.steps = int(cfg["sim"]["duration_s"] / cfg["sim"]["dt_s"]) + 1
        self.H = self.steps

    def _waypoints(self, i):
        W, H = self.g.size_x, self.g.size_y
        x0, x1 = i * W / self.n_agents, (i + 1) * W / self.n_agents
        lanes = np.arange(x0 + 0.9 * self.R, x1, 1.8 * self.R)
        lo, hi = self.kin.margin, H - self.kin.margin
        wps = []
        for j, lx in enumerate(lanes):
            wps += [(lx, lo), (lx, hi)] if j % 2 == 0 else [(lx, hi), (lx, lo)]
        return np.array(wps + wps[::-1])

    def plan(self, agent, step: int):
        wps = self._waypoints(agent.id)
        k = 0
        x, y, h = agent.x, agent.y, agent.h
        out = np.empty((self.steps - step, 3))
        for s in range(len(out)):
            if np.hypot(wps[k][0] - x, wps[k][1] - y) < 1.5 * self.kin.r_min:
                k = (k + 1) % len(wps)
            x, y, h = self.kin.rollout(x, y, h, 1, goals=wps[k][None])[0, 0]
            out[s] = x, y, h
        return out

